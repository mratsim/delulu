use super::*;
use crate::pipelines::DomNode;
use crate::pipelines::parse_html;

/// Helper: create a simple document with text content
fn make_doc(text_len: usize) -> DomNode {
    let text = "x".repeat(text_len);
    DomNode::Element {
        tag: "html".to_string(),
        attrs: vec![],
        children: vec![DomNode::Element {
            tag: "body".to_string(),
            attrs: vec![],
            children: vec![DomNode::Text(text)],
            scores: std::collections::HashMap::new(),
            metadata: std::collections::HashMap::new(),
        }],
        scores: std::collections::HashMap::new(),
        metadata: std::collections::HashMap::new(),
    }
}

/// A pass that removes ALL text content (simulates aggressive removal)
fn remove_all_text(node: &mut DomNode) {
    if let DomNode::Element { children, .. } = node {
        children.clear();
        children.push(DomNode::new_element("p"));
    }
}

/// A pass that removes NO text content (simulates safe pass)
fn noop_pass(_node: &mut DomNode) {}

/// Recovery: full restore
fn full_restore(node: &mut DomNode, backup: &DomNode) {
    *node = backup.clone();
}

#[test]
fn test_with_backup_threshold_triggered() {
    // 5x threshold: if new_len * 5 <= old_len, restore
    // old_len = 100, new_len = 10, threshold = 5
    // 10 * 5 = 50 <= 100 -> triggered
    let mut doc = make_doc(100);
    with_backup(&mut doc, remove_all_text, 5, full_restore);
    // Should be restored to original (backup)
    assert_eq!(
        doc.text_len(),
        100,
        "should be restored when threshold triggered"
    );
}

#[test]
fn test_with_backup_threshold_not_triggered() {
    // old_len = 100 -> new_len = 60; 60 * 5 = 300 > 100 -> NOT restored
    let restored = std::cell::Cell::new(false);
    let mut doc = make_doc(100);
    with_backup(
        &mut doc,
        |n| *n = make_doc(60),
        5,
        |_, _| restored.set(true),
    );
    assert!(
        !restored.get(),
        "recovery must NOT run when new_len*threshold > old_len"
    );
    assert_eq!(doc.text_len(), 60, "modified tree must be kept");
}

#[test]
fn test_with_backup_overflow_safe() {
    // new_len=10, threshold=usize::MAX -> 10 * MAX overflows usize ->
    // checked_mul returns None -> keep modified tree (no restore, no panic)
    let restored = std::cell::Cell::new(false);
    let mut doc = make_doc(10);
    with_backup(&mut doc, noop_pass, usize::MAX, |_, _| restored.set(true));
    assert!(
        !restored.get(),
        "overflow must keep modified tree (no restore)"
    );
    assert_eq!(doc.text_len(), 10, "tree unchanged on overflow");
}

#[test]
fn test_with_backup_zero_threshold() {
    // threshold = 0: new_len * 0 = 0 <= old_len always -> always restore
    let restored = std::cell::Cell::new(false);
    let mut doc = make_doc(100);
    with_backup(
        &mut doc,
        |n| *n = make_doc(10),
        0,
        |node, backup| {
            *node = backup.clone();
            restored.set(true);
        },
    );
    assert!(restored.get(), "zero threshold must always restore");
    assert_eq!(doc.text_len(), 100, "tree restored to original length");
}

#[test]
fn test_backup_restore_does_not_reintroduce_cleaned_tags() {
    // Regression: backup restore must not re-introduce cleaned tags.
    // Build a doc with <script>, <aside> (cleaned tags) and <p> (content).
    // Include lots of cleaned content so the cleaning pass removes >=80% of
    // the text, forcing with_backup's 5x threshold to trigger a restore.
    let html = "<html><body><script>alert(1)alert(2)alert(3)alert(4)alert(5)alert(6)</script><aside>sidebar one two three four five six</aside><p>main content here</p></body></html>";
    let mut doc = parse_html(html).unwrap();

    // The production cleaning pass: walk + tf_remove_cleaned.
    let cleaning_pass = |n: &mut DomNode| walk_pre_mut(n, &|n| tf_remove_cleaned(n));

    // Sanity: cleaning alone removes the cleaned tags but keeps content.
    let mut cleaned = doc.clone();
    cleaning_pass(&mut cleaned);
    assert!(
        !cleaned.text_content().contains("sidebar"),
        "<aside> should be removed by tf_remove_cleaned"
    );
    assert!(
        !cleaned.text_content().contains("alert"),
        "<script> should be removed by tf_remove_cleaned"
    );
    assert!(
        cleaned.text_content().contains("main content here"),
        "content should survive cleaning"
    );

    // Exercise the REAL production helper `with_backup` with the production
    // recovery closure (full restore + re-clean), exactly as generated by
    // `with_backup_wrapper!`. The pass removes >=80% of the text, so the
    // threshold triggers and recovery restores the UNCLEANED backup and
    // re-applies tf_remove_cleaned.
    with_backup(&mut doc, cleaning_pass, 5, |node, backup| {
        *node = backup.clone();
        walk_pre_mut(node, &|n| tf_remove_cleaned(n));
    });

    // After restore + re-clean, cleaned tags must still be gone,
    // and content must survive.
    assert!(
        !doc.text_content().contains("sidebar"),
        "cleaned tags must not reappear after restore"
    );
    assert!(
        !doc.text_content().contains("alert"),
        "script must not reappear after restore"
    );
    assert!(
        doc.text_content().contains("main content here"),
        "content should be preserved"
    );
}

